import { test } from 'node:test';
import assert from 'node:assert/strict';
import { toCaptions, toSpeech, transcode } from '../hook/voice.mjs';
import { stopOutput } from '../hook/memomind-voice-hook.mjs';

test('toSpeech drops code, links and Markdown noise', () => {
  const md = '## Done\n\nI fixed **two** bugs in `relay.js`:\n\n```js\nconst x = 1;\n```\n\n- see https://example.com/pr/2\n- [the docs](https://x.y)';
  const speech = toSpeech(md);
  assert.equal(speech, 'Done I fixed two bugs in relay.js: (code omitted) see a link the docs');
});

test('toSpeech trims long replies at a sentence and points to the screen', () => {
  const speech = toSpeech('This is one sentence. '.repeat(60));
  assert.ok(speech.length < 700);
  assert.match(speech, /sentence\. The rest is on your screen\.$/);
});

test('toCaptions keeps structure but drops code bodies', () => {
  assert.equal(toCaptions('# Title\n\n**Bold** and `code`\n\n```\nlong\n```'), 'Title\n\nBold and code\n\n[code]');
});

test('stopOutput blocks the stop and quotes the reply safely', () => {
  const output = stopOutput('say "hi" to the team');
  assert.equal(output.decision, 'block');
  assert.match(output.reason, /replied by voice from their MemoMind glasses: "say \\"hi\\" to the team"/);
});

test('transcode round-trips audio through ffmpeg', async (t) => {
  const { spawnSync } = await import('node:child_process');
  const probe = spawnSync('ffmpeg', ['-version']);
  if (probe.status !== 0) return t.skip('ffmpeg not installed');
  // 0.5 s of silence as 16 kHz WAV, generated by ffmpeg itself.
  const gen = spawnSync('ffmpeg', ['-loglevel', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=16000:cl=mono', '-t', '0.5', '-f', 'wav', 'pipe:1']);
  const wav = gen.stdout;
  const ogg = await transcode(wav, ['-c:a', 'libopus', '-b:a', '24k', '-f', 'ogg']);
  assert.equal(ogg.subarray(0, 4).toString(), 'OggS');
  const back = await transcode(ogg, ['-ar', '16000', '-ac', '1', '-f', 'wav']);
  assert.equal(back.subarray(0, 4).toString(), 'RIFF');
  await assert.rejects(transcode(Buffer.from('not audio'), ['-f', 'wav']), /ffmpeg exited/);
});

test('pcmToWav writes a valid header with real chunk sizes', async () => {
  const { pcmToWav } = await import('../hook/voice.mjs');
  const wav = pcmToWav(Buffer.alloc(32000));
  assert.equal(wav.toString('ascii', 0, 4), 'RIFF');
  assert.equal(wav.readUInt32LE(4), 36 + 32000);
  assert.equal(wav.readUInt32LE(24), 16000);
  assert.equal(wav.readUInt32LE(40), 32000);
});
